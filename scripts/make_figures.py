# Fig. 7 -- C2: spectral affinity vs cross-domain ranking transfer
# ---------------------------------------------------------------------------
def fig7(pool_dir, domains, seeds=(7,)):
    mean_fp, mean_rank = {}, {}
    for d in domains:
        fps, ranks = [], []
        for s in seeds:
            p = os.path.join(pool_dir, f"{d}__seed{s}.npz")
            if not os.path.exists(p):
                continue
            z = np.load(p, allow_pickle=True)
            X, Y, P = z["X"], z["Y"], z["P"]
            itr, ite = z["idx_train"], z["idx_test"]
            fp = Fingerprint(K=32); fp.fit(X[itr])
            PHI = fp.transform(X)
            fps.append(PHI[ite].mean(axis=0))
            lm = np.mean((P[ite] - Y[ite][:, None, :]) ** 2, axis=2)
            ranks.append(lm.mean(axis=0))
        if fps:
            mean_fp[d] = np.mean(fps, axis=0)
            mean_rank[d] = np.mean(ranks, axis=0)
    ks = [d for d in domains if d in mean_fp]
    if len(ks) < 4:
        print("  Fig7 skipped (not enough domains)")
        return
    S = np.stack([mean_fp[k][:32] for k in ks])
    S = (S - S.mean(0)) / (S.std(0) + 1e-9)
    G = S @ S.T
    sq = np.diag(G)
    dist = np.sqrt(np.maximum(sq[:, None] + sq[None, :] - 2 * G, 0))
    R = np.stack([mean_rank[k] for k in ks])
    corr = np.array([[sps.spearmanr(R[i], R[j]).statistic for j in range(len(ks))]
                     for i in range(len(ks))])
    iu = np.triu_indices(len(ks), 1)
    x, y = dist[iu], corr[iu]
    fig, ax = plt.subplots(figsize=(3.6, 3.0),
                           gridspec_kw=dict(left=0.16, right=0.97, top=0.92, bottom=0.16))
    fam = {"EPF-NP": "power", "EPF-PJM": "power", "EPF-BE": "power",
           "EPF-FR": "power", "EPF-DE": "power", "ETTh1": "sensor",
           "ETTh2": "sensor", "ETTm1": "sensor", "ETTm2": "sensor",
           "Weather": "climate", "ECL": "load"}
    same = np.array([fam[ks[i]] == fam[ks[j]] for i, j in zip(*iu)])
    ax.scatter(x[same], y[same], s=16, color=PALETTE["blue_main"],
               label="within family", zorder=3)
    ax.scatter(x[~same], y[~same], s=16, color=PALETTE["neutral_light"],
               label="across families", zorder=3)
    rho = sps.spearmanr(x, y)
    b = np.polyfit(x, y, 1)
    xs = np.linspace(x.min(), x.max(), 50)
    ax.plot(xs, np.polyval(b, xs), color=PALETTE["red_strong"], lw=1.0)
    ax.set_xlabel("spectral distance between domains")
    ax.set_ylabel("Spearman correlation of\n expert loss rankings")
    ax.legend(fontsize=5.8)
    ax.text(0.98, 0.05, f"Spearman = {rho.statistic:.2f}, p = {rho.pvalue:.1e}",
            transform=ax.transAxes, ha="right", fontsize=6)
    save(fig, "Fig7_spectral_affinity_monotonicity")


def fig8_ladder():
    """Dose-response: gain over the best causal baseline along the ladder."""
    p = os.path.join(SUMMARY, "ladder.csv")
    if not os.path.exists(p):
        print("  Fig8 skipped (no ladder table)")
        return
    import csv as _csv
    with open(p, encoding="utf-8") as f:
        rows = list(_csv.DictReader(f))
    rungs = [r["rung"] for r in rows]
    mean = np.array([float(r["gain_pct_mean"]) for r in rows])
    med = np.array([float(r["gain_pct_median"]) for r in rows])
    lo = np.array([float(r["gain_pct_min"]) for r in rows])
    hi = np.array([float(r["gain_pct_max"]) for r in rows])
    x = np.arange(len(rungs))
    fig, ax = plt.subplots(figsize=(3.4, 2.5),
                           gridspec_kw=dict(left=0.19, right=0.97, top=0.90,
                                            bottom=0.28))
    ax.axhline(0, color=PALETTE["neutral_mid"], lw=0.6)
    ax.vlines(x, lo, hi, color=PALETTE["neutral_light"], lw=1.6, zorder=1)
    ax.plot(x, mean, "-o", color=PALETTE["blue_main"], ms=3.6, lw=1.2, zorder=3,
            label="mean over seeds")
    ax.plot(x, med, "--s", color=PALETTE["red_strong"], ms=3.0, lw=1.0, zorder=2,
            label="median")
    ax.axhline(8.0, color=PALETTE["red_strong"], lw=0.7, ls=":", zorder=0)
    ax.set_xticks(x)
    ax.set_xticklabels(rungs, fontsize=6.0, rotation=0)
    ax.set_xlabel("ladder rung (increasing multi-source mixing)  $\\rightarrow$", fontsize=6.2)
    ax.set_ylabel("gain over best causal\nbaseline (%)", fontsize=6.2)
    ax.legend(fontsize=5.4, loc="upper left", frameon=False)
    save(fig, "Fig8_nonstationarity_ladder")


