# Fig. 3 -- hero panel: cumulative streaming error
# ---------------------------------------------------------------------------
def fig3(D, domains):
    base_order = ["B1_frozen_static", "B2_monthly_retrain", "B4_hedge",
                  "B6_adwin_retrain", "B7_online_meta", "B5_best_expert"]
    fig = plt.figure(figsize=(7.09, 3.5))
    gs = fig.add_gridspec(1, 2, width_ratios=[2.0, 1.0], wspace=0.28,
                          left=0.075, right=0.985, top=0.90, bottom=0.14)
    axA = fig.add_subplot(gs[0])
    axB = fig.add_subplot(gs[1])

    # pooled cumulative curves, normalised per (domain, seed) by the frozen static
    def norm_curve(key, d, s):
        rec = D[(d, s)]
        ref = np.cumsum(rec["arms"]["B1_frozen_static"]["loss"])
        return np.cumsum(rec["arms"][key]["loss"]) / ref

    keys = ["FULL"] + [b for b in base_order]
    colors = {k: c for k, c in zip(keys, [PALETTE["red_strong"], PALETTE["neutral_light"],
                                          PALETTE["neutral_mid"], PALETTE["blue_secondary"],
                                          PALETTE["violet"], PALETTE["teal"],
                                          PALETTE["neutral_black"]])}
    for k in keys:
        curves = []
        for (d, s) in D:
            if k in D[(d, s)]["arms"]:
                c = norm_curve(k, d, s)
                curves.append(np.interp(np.linspace(0, 1, 200),
                                        np.linspace(0, 1, len(c)), c))
        C = np.array(curves)
        m = C.mean(axis=0)
        sd = C.std(axis=0) / np.sqrt(len(C))
        x = np.linspace(0, 1, 200)
        axA.plot(x, m, color=colors[k], lw=1.4 if k == "FULL" else 0.9,
                 label=("CerebroCast" if k == "FULL" else k.replace("_", " ")),
                 zorder=3 if k == "FULL" else 2)
        if k == "FULL":
            axA.fill_between(x, m - 1.96 * sd, m + 1.96 * sd,
                             color=colors[k], alpha=0.18, lw=0)
    axA.axhline(1.0, color=PALETTE["neutral_dark"], lw=0.6, ls=":")
    axA.set_xlabel("fraction of the test stream")
    axA.set_ylabel("cumulative loss / frozen static combination")
    axA.legend(loc="upper left", fontsize=5.8, ncol=2, handlelength=1.4)
    panel_label(axA, "a")

    gains = []
    BASELINES = ["B1_frozen_static", "B2_monthly_retrain", "B3_fforma",
                 "B4_hedge", "B5_best_expert", "B6_adwin_retrain",
                 "B7_online_meta"]
    for d in domains:
        g = []
        for s in SEEDS:
            if (d, s) not in D:
                continue
            arms = D[(d, s)]["arms"]
            bl = {b: np.mean(arms[b]["loss"]) for b in BASELINES if b in arms}
            if not bl:
                continue
            best = min(bl.values())
            g.append(100 * (best - np.mean(arms["FULL"]["loss"])) / best)
        if g:
            gains.append((d, np.mean(g), np.std(g) / np.sqrt(len(g))))
    gains.sort(key=lambda t: -t[1])
    axB.barh([g[0] for g in gains], [g[1] for g in gains],
             xerr=[1.96 * g[2] for g in gains], color=PALETTE["red_strong"],
             height=0.65, error_kw=dict(lw=0.6, capsize=2, ecolor=PALETTE["neutral_dark"]))
    axB.axvline(0, color=PALETTE["neutral_dark"], lw=0.7)
    axB.axvline(8, color=PALETTE["blue_main"], lw=0.7, ls="--")
    axB.set_xlabel("gain vs best baseline (%)")
    axB.invert_yaxis()
    panel_label(axB, "b")
    save(fig, "Fig3_cumulative_streaming_error")


