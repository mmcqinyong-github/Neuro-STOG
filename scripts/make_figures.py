def load_stream(domains, seeds) -> Dict:
    out = {}
    for d in domains:
        for s in seeds:
            p = os.path.join(STREAM, f"{d}__seed{s}.npz")
            if not os.path.exists(p):
                continue
            z = np.load(p, allow_pickle=True)
            meta = json.loads(str(z["__meta__"]))
            arms = {}
            for k in z.files:
                if k == "__meta__" or "__" not in k:
                    continue
                an, fn = k.split("__", 1)
                arms.setdefault(an, {})[fn] = z[k]
            out[(d, s)] = dict(meta=meta, arms=arms)
    return out


